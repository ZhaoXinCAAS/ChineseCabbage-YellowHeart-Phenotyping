# ===================== Reading and verifying =====================
def ecdf(x):
    x = np.sort(np.asarray(x, dtype=float))
    return x, np.arange(1, x.size + 1) / x.size


def wilson_ci(k, n, z=1.959964):
    if n == 0:
        return np.nan, np.nan
    p = k / n
    den = 1.0 + z * z / n
    centre = (p + z * z / (2.0 * n)) / den
    margin = z / den * np.sqrt(p * (1.0 - p) / n + z * z / (4.0 * n * n))
    return max(0.0, centre - margin), min(1.0, centre + margin)


def holm(pvals):
    p = np.asarray(pvals, dtype=float)
    m = p.size
    order = np.argsort(p)
    adj = np.empty(m, dtype=float)
    prev = 0.0
    for rank, idx in enumerate(order):
        val = min(1.0, (m - rank) * p[idx])
        val = max(val, prev)
        adj[idx] = val
        prev = val
    return adj


def cliffs_delta(a, b):
    a = np.asarray(a, dtype=float)
    b = np.asarray(b, dtype=float)
    gt = np.sum(a[:, None] > b[None, :])
    lt = np.sum(a[:, None] < b[None, :])
    return float(gt - lt) / (a.size * b.size)


def jt_stat(groups):
    """
    [Repair2]: Jonckheere-Terpstra Statistics(Check for decreasing trends: easy > typical > challenging)
    When the front group (i) of IoU Greater than the next group (j) accumulated over time. 
    """
    s = 0.0
    for i in range(len(groups)):
        for j in range(i + 1, len(groups)):
            a, b = groups[i], groups[j]
            s += np.sum(a[:, None] > b[None, :])
            s += 0.5 * np.sum(a[:, None] == b[None, :])
    return float(s)


def jt_test(groups, n_perm=N_PERM, seed=SEED):
    """permutation test, Unilateral(The higher the difficulty IoU The lower -> The further back the group sequence is, the smaller the value is.). """
    rng = np.random.default_rng(seed)
    obs = jt_stat(groups)
    sizes = [len(g) for g in groups]
    pool = np.concatenate(groups).copy()
    cnt = 0
    for _ in range(n_perm):
        rng.shuffle(pool)
        idx = np.cumsum([0] + sizes)
        gs = [pool[idx[k]:idx[k + 1]] for k in range(len(sizes))]
        if jt_stat(gs) >= obs - 1e-12:
            cnt += 1
    return obs, (cnt + 1) / (n_perm + 1)


def cochran_armitage(fail, n, scores):
    """[Repair3]: Trend test of failure rate as a function of ordered stratification(Add zero variance protection, Prevent all 0 Failure rate reporting error). """
    fail = np.asarray(fail, dtype=float)
    n = np.asarray(n, dtype=float)
    scores = np.asarray(scores, dtype=float)
    total_n = n.sum()
    total_r = fail.sum()
    if total_n == 0 or total_r == 0 or total_r == total_n:
        return 0.0, 1.0
    p = total_r / total_n
    t = np.sum(scores * (fail - n * p))
    var = p * (1.0 - p) * (
        np.sum(n * scores ** 2) - (np.sum(n * scores)) ** 2 / total_n
    )
    if var <= 0:
        return 0.0, 1.0
    z = t / np.sqrt(var)
    return z, 2.0 * norm.sf(abs(z))


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="XLSX or CSV with filename, category, and IoU.")
    parser.add_argument("output_dir", type=Path, help="Directory for SVG and CSV output.")
    args = parser.parse_args()
    input_path = args.input
    args.output_dir.mkdir(parents=True, exist_ok=True)
    out_svg = args.output_dir / "Fig_ECDF_IoU.svg"
    out_csv = args.output_dir / "Fig_ECDF_IoU_stats.csv"
    CATS = CATEGORIES.copy()

    if input_path.suffix.lower() == ".csv":
        df = pd.read_csv(input_path)
    else:
        df = pd.read_excel(input_path, sheet_name=0)
    # [Repair1]: Automatically remove spaces and convert all column names to all lowercase, Perfectly compatible ioU / IoU / Dice Wait for writing
    df.columns = [str(c).strip().lower() for c in df.columns]

    if "filename" not in df:
        df = df.rename(columns={"image_id": "filename"})
    if "category" not in df:
        df = df.rename(columns={"yellow_level": "category"})
    need = {"filename", "iou", "category"}
    missing = need - set(df.columns)
    if missing:
        raise ValueError(f"missing column: {sorted(missing)}; actual column: {list(df.columns)}")

    df["filename"] = df["filename"].astype(str).str.strip()
    df["category"] = df["category"].astype(str).str.strip().str.lower()
    df["iou"] = pd.to_numeric(df["iou"], errors="coerce")

    n_nan = int(df["iou"].isna().sum())
    print(f"[check] iou Missing {n_nan} OK, Culled")
    df = df[df["iou"].notna()].copy()

    if not df["iou"].between(0, 1).all():
        bad = df.loc[~df["iou"].between(0, 1), ["filename", "iou"]]
        raise ValueError(f"IoU Not here [0,1]: \n{bad.head()}")

    unknown = sorted(set(df["category"]) - set(CATS))
    if unknown:
        raise ValueError(f"Unidentified category: {unknown}")

    dups = df["filename"][df["filename"].duplicated()].tolist()
    if dups:
        print(f"[check] Repeat filename {len(dups)} Article, For example: {dups[:3]}")

    if not AMBIGUOUS_HAS_GT:
        print("[check] AMBIGUOUS_HAS_GT=False, ambiguous Group does not participate IoU Figure")
        CATS = [c for c in CATS if c != "ambiguous"]

    for c in CATS:
        if not (df["category"] == c).any():
            raise ValueError(f"{c} Group is empty, please check category spelling")

    if CLUSTER_BY_HEAD:
        # Change the last _1, _2, _3 Remove equal section numbers, grouped into the same leaf ball head_id
        df["head_id"] = df["filename"].str.replace(r"_\d+$", "", regex=True)
    else:
        df["head_id"] = df["filename"]

    print("\n[check] number of images / Number of heads: ")
    print(df.groupby("category").agg(n_images=("iou", "size"),
                                     n_heads=("head_id", "nunique")).to_string())

    # ===================== Utility function =====================
    # ===================== Summary by type =====================
    # head level: Take the average of multiple slices of the same ball first, for hypothesis testing, avoid false duplication
    head = (df.groupby(["category", "head_id"], as_index=False)["iou"]
              .mean())

    rows = []
    for cat in CATS:
        v = df.loc[df.category == cat, "iou"].values
        h = head.loc[head.category == cat, "iou"].values
        k = int(np.sum(v <= FAIL_IOU))
        lo, hi = wilson_ci(k, v.size)
        rows.append({
            "category": cat,
            "n_images": v.size,
            "n_heads": h.size,
            "mean": v.mean(),
            "sd": v.std(ddof=1) if v.size > 1 else np.nan,
            "median": np.median(v),
            "q1": np.quantile(v, 0.25),
            "q3": np.quantile(v, 0.75),
            "fail_n": k,
            "fail_rate": k / v.size,
            "fail_lo": lo,
            "fail_hi": hi,
        })

    stats_df = pd.DataFrame(rows)
    stats_df.to_csv(out_csv, index=False, encoding="utf-8-sig")

    print("\n===== Summary by type(image level) =====")
    print(stats_df.round(3).to_string(index=False))

    # ===================== Pairs KS + Holm(head level) =====================
    print("\n===== Pairwise KS on head-level means (Holm-corrected) =====")
    pairs = list(combinations(CATS, 2))
    ks_rows = []
    for a, b in pairs:
        xa = head.loc[head.category == a, "iou"].values
        xb = head.loc[head.category == b, "iou"].values
        stat, p = ks_2samp(xa, xb, method="asymp")
        ks_rows.append((a, b, stat, p, cliffs_delta(xa, xb)))

    adj = holm([r[3] for r in ks_rows])
    for (a, b, stat, p, delta), p_adj in zip(ks_rows, adj):
        print(f"{a:12s} vs {b:12s}: D={stat:.3f}, P={p:.2e}, "
              f"P_Holm={p_adj:.2e}, Cliff's d={delta:+.2f}")

    # ===================== Trend test =====================
    print("\n===== Trend tests =====")
    gs = [head.loc[head.category == c, "iou"].values for c in ORDERED]
    jt, p_jt = jt_test(gs)
    print(f"Jonckheere-Terpstra (head-level IoU, {' -> '.join(ORDERED)}): "
          f"JT={jt:.0f}, P={p_jt:.4f}")

    fail = [int(np.sum(df.loc[df.category == c, "iou"] <= FAIL_IOU)) for c in ORDERED]
    nn = [int((df.category == c).sum()) for c in ORDERED]
    z_ca, p_ca = cochran_armitage(fail, nn, np.arange(len(ORDERED)))
    print(f"Cochran-Armitage (image-level failure rate): Z={z_ca:.2f}, P={p_ca:.2e}")
    print("  Note: CA for image level, exploratory; The main trend conclusion uses the above JT. ")

    # ===================== Drawing =====================
    fig, ax = plt.subplots(figsize=(FIG_W, FIG_H))

    for cat in CATS:
        v = df.loc[df.category == cat, "iou"].values
        x, y = ecdf(v)
        fr = np.mean(v <= FAIL_IOU)
        ax.step(
            x, y, where="post",
            color=COLORS[cat], linewidth=1.5, solid_capstyle="butt",
            label=f"{cat} (n={v.size}; {fr:.0%} fail)",
            zorder=3,
        )
        ax.plot(
            FAIL_IOU, fr, marker="o", markersize=3.6,
            markerfacecolor="white", markeredgecolor=COLORS[cat],
            markeredgewidth=0.9, linestyle="none", zorder=6,
        )

    ax.axvline(FAIL_IOU, color="0.45", linewidth=0.7,
               linestyle=(0, (3, 3)), zorder=0)
    ax.text(FAIL_IOU, 1.008, "IoU = 0.5", ha="center", va="bottom",
            fontsize=BASE_FONT - 1.0, color="0.35")

    ax.set_xlabel("IoU (automatic vs. manual reference)")
    ax.set_ylabel("Cumulative probability")
    ax.set_xlim(0.0, 1.0)
    ax.set_ylim(0.0, 1.03)
    ax.set_xticks(np.arange(0.0, 1.01, 0.2))
    ax.set_yticks(np.arange(0.0, 1.01, 0.25))

    ax.legend(loc="lower right", frameon=False, handlelength=1.6,
              labelspacing=0.35, borderaxespad=0.25)

    fig.subplots_adjust(left=0.135, right=0.985, bottom=0.145, top=0.965)
    fig.savefig(out_svg, format="svg")
    plt.close(fig)

    print(f"\nSVG : {out_svg}")
    print(f"CSV : {out_csv}")
    print("SVG The text in remains as <text>, can be directly Illustrator / Inkscape Ligai. ")

if __name__ == "__main__":
    main()
